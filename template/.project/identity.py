"""Read-only identity/provenance checks, with no dependencies beyond Python 3.9.

This receipt detects inconsistent project records; it is not a signed attestation.
The TOML identity reader intentionally accepts the plain table/key/string syntax
generated by this template. It rejects unsupported syntax rather than guessing.
The package manager remains responsible for full TOML and dependency validation.
"""

import json
from pathlib import Path
import re
from urllib.parse import urlsplit

NAME = re.compile(r"[a-z][a-z0-9]*(?:-[a-z0-9]+)*")
VERSION = re.compile(r"(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)")
HASH = re.compile(r"(?:[0-9a-f]{40}|[0-9a-f]{64})")
RECEIPT_KEYS = {
    "receipt_version", "foundation_version", "source_path", "source_ref", "source_commit",
    "project_name", "package_name", "profile", "runtime",
}


def _fail(message):
    raise ValueError("Project identity: " + message)


def _text(path):
    try:
        return path.read_text(encoding="utf-8")
    except (OSError, UnicodeError) as exc:
        _fail(f"Cannot read {path.name}: {exc}. Restore the generated contract file.")


def _unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            _fail(f"Duplicate JSON key {key!r}; remove the ambiguity before proceeding.")
        result[key] = value
    return result


def _json(path):
    try:
        result = json.loads(_text(path), object_pairs_hook=_unique_object)
    except json.JSONDecodeError as exc:
        _fail(f"{path.name} must contain a JSON object: {exc.msg}. "
              "Restore it from Git or complete a reviewed Copier update; do not edit lineage by hand.")
    if not isinstance(result, dict):
        _fail(f"{path.name} must contain an object.")
    return result


def _plain(value):
    return isinstance(value, str) and bool(value.strip()) and not any(ord(c) < 32 for c in value)


def _source_path(value):
    if not _plain(value):
        return False
    if Path(value).is_absolute():
        return True
    if re.fullmatch(r"git@[A-Za-z0-9.-]+:[A-Za-z0-9_.-]+/[A-Za-z0-9_./-]+", value):
        return True
    try:
        parsed = urlsplit(value)
        parsed.port
    except ValueError:
        return False
    return (parsed.scheme in {"https", "git+https", "ssh", "git+ssh"}
            and bool(parsed.hostname) and bool(parsed.path.strip("/"))
            and not parsed.query and not parsed.fragment and not parsed.password
            and not any(c.isspace() for c in value))


def _uncomment(line, path):
    """Ignore a TOML comment without mistaking a quoted # for its start."""
    quote = None
    escaped = False
    for index, char in enumerate(line):
        if quote:
            if quote == '"' and char == "\\" and not escaped:
                escaped = True
                continue
            if char == quote and not escaped:
                quote = None
            escaped = False
        elif char == "#":
            return line[:index].strip()
        elif char in "\"'":
            if line[index:index + 3] == char * 3:
                _fail(f"Unsupported TOML multiline string in {path.name}; use single-line strings "
                      "for this foundation's dependency-free identity reader.")
            quote = char
    return line.strip()


def _literal(value, path, key):
    match = re.fullmatch(r'''(?:"([^"\\]*)"|'([^']*)')''', value)
    if not match:
        _fail(f"Unsupported TOML {key} syntax in {path.name}; use an unescaped, "
              "single-line quoted string and an unquoted key.")
    return match.group(1) if match.group(1) is not None else match.group(2)


def _project_name(path):
    in_project = False
    found_table = False
    name = None
    for raw in _text(path).splitlines():
        line = _uncomment(raw, path)
        if not line:
            continue
        if line.startswith("["):
            in_project = bool(re.fullmatch(r"\[\s*project\s*\]", line))
            if in_project:
                if found_table:
                    _fail(f"Duplicate [project] table in {path.name}.")
                found_table = True
            continue
        if in_project:
            assignment = re.fullmatch(r"name\s*=\s*(.*)", line)
            if assignment:
                if name is not None:
                    _fail(f"Duplicate project name in {path.name}.")
                name = _literal(assignment.group(1), path, "[project].name")
            elif line.startswith(('"name"', "'name'")):
                _fail(f"Unsupported quoted name key in {path.name}; use name = \"project-name\".")
    if name is None:
        _fail(f"{path.name} needs a plain [project] table with name = \"project-name\". "
              "Dotted/quoted identity keys and multiline strings are unsupported by this reader.")
    return name


def _uv_packages(path):
    packages = []
    current = None
    direct_fields = False
    for raw in _text(path).splitlines():
        line = _uncomment(raw, path)
        if not line:
            continue
        if line.startswith("["):
            if re.fullmatch(r"\[\[\s*package\s*\]\]", line):
                current = {}
                packages.append(current)
                direct_fields = True
            else:
                direct_fields = False
            continue
        if not direct_fields or current is None:
            continue
        assignment = re.fullmatch(r"(name|source)\s*=\s*(.*)", line)
        if not assignment:
            continue
        key, value = assignment.groups()
        if key in current:
            _fail(f"Duplicate package {key} in {path.name}; regenerate the lock explicitly.")
        if key == "name":
            current[key] = _literal(value, path, "package.name")
        else:
            if not value.startswith("{") or not value.endswith("}"):
                _fail(f"Unsupported source syntax in {path.name}; regenerate with the pinned uv.")
            current[key] = value
    if not packages or any("name" not in item or "source" not in item for item in packages):
        _fail(f"{path.name} needs named [[package]] entries with inline source tables; "
              "regenerate with the pinned uv.")
    return packages


def _normalized(name):
    return re.sub(r"[-_.]+", "-", name).lower()


def inspect_identity(root, meta):
    """Validate recorded identity and return the authoritative runtime pins.

    No source checkout access, installation, subprocess, or network is needed.
    Application version and dependency graph evolution remain project-owned.
    """
    root = Path(root)
    receipt = _json(root / ".project/template.json")
    if (set(receipt) != RECEIPT_KEYS or type(receipt.get("receipt_version")) is not int
            or receipt["receipt_version"] != 1):
        _fail(".project/template.json has an unsupported receipt structure; "
              "restore it or complete a reviewed foundation update.")
    name = receipt["project_name"]
    profile = receipt["profile"]
    if (not isinstance(name, str) or not NAME.fullmatch(name) or not 2 <= len(name) <= 48
            or receipt["package_name"] != name.replace("-", "_")
            or not isinstance(profile, str) or profile not in {"typescript-web", "python-service"}):
        _fail(".project/template.json has invalid project identity/profile fields.")
    if not isinstance(receipt["foundation_version"], str) or not VERSION.fullmatch(receipt["foundation_version"]):
        _fail(".project/template.json needs a valid foundation_version.")
    if not _source_path(receipt["source_path"]):
        _fail("source_path must be absolute for a local template (or an explicit supported Git URL); "
              "regenerate using an absolute source path. Do not rewrite Copier lineage manually.")
    if (not _plain(receipt["source_ref"]) or not isinstance(receipt["source_commit"], str)
            or not HASH.fullmatch(receipt["source_commit"]) or not receipt["source_commit"].strip("0")):
        _fail("Template source ref/hash is missing or invalid; generate from a versioned Git "
              "template using an explicit release or commit. Unknown source provenance is unsupported.")
    if not isinstance(meta, dict):
        _fail(".project/project.json must contain an object.")
    for field, receipt_field in {"name": "project_name", "package_name": "package_name",
                                 "profile": "profile", "foundation_version": "foundation_version"}.items():
        if meta.get(field) != receipt[receipt_field]:
            _fail(f".project/project.json {field} disagrees with .project/template.json; "
                  "restore the project identity or finish the reviewed Copier update.")

    lineage = _json(root / ".copier-answers.yml")
    for field, receipt_field in {"_src_path": "source_path", "_commit": "source_ref",
                                 "project_name": "project_name", "profile": "profile"}.items():
        if lineage.get(field) != receipt[receipt_field]:
            _fail(f".copier-answers.yml {field} disagrees with template provenance; "
                  "restore lineage from Git or finish the reviewed Copier update, never hand-edit it.")
    if "package_name" in lineage and lineage["package_name"] != receipt["package_name"]:
        _fail(".copier-answers.yml package_name disagrees with template provenance.")

    pins = receipt["runtime"]
    expected = {"runner_python_min", "node", "npm"} if profile == "typescript-web" else {
        "runner_python_min", "python", "uv"}
    if not isinstance(pins, dict) or set(pins) != expected or pins.get("runner_python_min") != "3.9":
        _fail(".project/template.json runtime pins have an unsupported structure.")
    if any(not isinstance(pins[key], str) or not VERSION.fullmatch(pins[key])
           for key in expected - {"runner_python_min"}):
        _fail(".project/template.json runtime versions must be exact numeric major.minor.patch pins.")

    if profile == "typescript-web":
        manifest = _json(root / "package.json")
        lock = _json(root / "package-lock.json")
        packages = lock.get("packages")
        lock_root = packages.get("") if isinstance(packages, dict) else None
        if (manifest.get("name") != name or lock.get("name") != name
                or not isinstance(lock_root, dict) or lock_root.get("name") != name):
            _fail("package.json and both package-lock.json root names must match project metadata; "
                  "restore identity and explicitly refresh the lock after intended manifest changes.")
        if any(key.rsplit("node_modules/", 1)[-1] == name for key in packages if key):
            _fail("The project name collides with a locked npm dependency; choose a distinctive project name.")
        if _text(root / ".node-version").strip() != pins["node"]:
            _fail(".node-version disagrees with the template runtime pin; review the runtime update together.")
        if manifest.get("packageManager") != "npm@" + pins["npm"]:
            _fail("package.json packageManager disagrees with the template npm pin.")
    else:
        if _project_name(root / "pyproject.toml") != name:
            _fail("pyproject.toml [project].name must match project metadata.")
        packages = _uv_packages(root / "uv.lock")
        roots = [item for item in packages if re.fullmatch(
            r'''\{\s*editable\s*=\s*(?:"\."|'\.')\s*\}''', item["source"])]
        if len(roots) != 1 or roots[0]["name"] != name:
            _fail("uv.lock must contain exactly one editable root package named after project metadata; "
                  "refresh the lock explicitly with the pinned uv.")
        if sum(_normalized(item["name"]) == _normalized(name) for item in packages) != 1:
            _fail("The project name collides with a locked Python distribution; choose a distinctive project name.")
        if _text(root / ".python-version").strip() != pins["python"]:
            _fail(".python-version disagrees with the template runtime pin; review the runtime update together.")
    return dict(pins)
